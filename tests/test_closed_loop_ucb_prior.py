"""
Test closed-loop integration between System C (RF physics) and System B (ClassicalUCB1).
Verifies that:
1. Real IQ is generated by System C.
2. Pulse detector extracts pulses from real IQ.
3. System B's ClassicalUCB1 selects bands and updates its policy via rewards.
4. Decisions actually alter System C's dwell observation window.
"""
import math
import numpy as np
import pytest
from typing import List, Tuple, Optional

from vyapti_simulator.system_c.rf.simulator_engine import (
    RealTimeRFSimulator,
    SimulationEngineConfig,
)
from vyapti_simulator.system_c.rf.pulse_detector import (
    PulseDetector,
    PulseDetectorConfig,
    EmitterInfo,
)
from vyapti_simulator.system_c.rf.closed_loop import (
    BaseScheduler,
    Dwell,
    MissionState,
    MissionRunner,
)
from vyapti_simulator.system_a.synthetic_pdw.generator import SyntheticEmitterSpec
from vyapti_simulator.system_b.tsrd.policies.classical_ucb1 import ClassicalUCB1
from vyapti_simulator.system_b.tsrd.algorithm_interface import PublicState, PublicTransition


class UCBPriorScheduler(BaseScheduler):
    """Closed-loop adapter for the existing System B ClassicalUCB1 policy."""
    def __init__(
        self,
        bands_hz: List[Tuple[float, float]],
        dwell_ms: float = 10.0,
        seed: int = 42,
        exploration_coefficient: float = math.sqrt(2.0),
        reward_bounds: Tuple[float, float] = (-0.01, 1.0),
    ):
        if not bands_hz:
            raise ValueError("bands_hz must be non-empty")
        self.bands = bands_hz
        self.dwell_ms = float(dwell_ms)
        self.policy = ClassicalUCB1(
            bands=len(bands_hz),
            seed=seed,
            reward_bounds=reward_bounds,
            exploration_coefficient=exploration_coefficient,
        )
        self.last_action: Optional[int] = None
        self.slot = 0
        self.history_records = []

    def reset(self) -> None:
        self.policy.reset_episode(training=False)
        self.last_action = None
        self.slot = 0
        self.history_records = []

    def decide(self, state: MissionState) -> Dwell:
        # Observe reward from previous dwell
        if self.last_action is not None:
            hit = len(state.recent_pdws) > 0
            reward = 1.0 if hit else 0.0
            transition = PublicTransition(
                state=PublicState(self.slot, None),
                action=self.last_action,
                reward=reward,
                next_state=PublicState(self.slot + 1, None),
                terminated=False,
            )
            self.policy.observe(transition, training=False)
            self.history_records.append({
                "slot": self.slot,
                "action": self.last_action,
                "reward": reward,
                "hit": hit,
                "pdws_count": len(state.recent_pdws),
            })
            self.slot += 1

        action = self.policy.select_action(PublicState(self.slot, None), training=False)
        self.last_action = action
        band = self.bands[action]

        return Dwell(
            freq_start_hz=float(band[0]),
            freq_end_hz=float(band[1]),
            dwell_ms=self.dwell_ms,
            priority=0.5,
            reason=f"UCB-Prior band {action}",
        )


def test_closed_loop_ucb_prior():
    rng = np.random.default_rng(42)
    chirp_bw_hz = 1e6
    pulse_width_s = 10e-6

    det_cfg = PulseDetectorConfig(
        dsp_sample_rate_hz=10e6,
        tick_interval_s=1e-3,
        cfar_db=10.0,
        min_pulse_samples=3,
        carrier_freq_hz=3.0e9,
        chirp_bandwidth_hz=chirp_bw_hz,
        pulse_width_s=pulse_width_s,
    )
    eng_cfg = SimulationEngineConfig(
        dsp_sample_rate_hz=10e6,
        tick_interval_s=1e-3,
        snr_db=25.0,
    )

    # Place an emitter in Band 2: [3.02e9, 3.03e9)
    emitter_target_freq = 3.025e9
    specs = [
        SyntheticEmitterSpec(
            emitter_id=1,
            center_freq_hz=emitter_target_freq,
            pri_sec=1e-3,
            pulse_width_sec=pulse_width_s,
            chirp_bandwidth_hz=chirp_bw_hz,
            aoa_deg=45.0,
            snr_db=25.0,
            emitter_type="fixed_continuous",
        )
    ]

    engine = RealTimeRFSimulator(config=eng_cfg, rng=rng)
    detector = PulseDetector(
        config=det_cfg,
        emitter_map={1: EmitterInfo(emitter_target_freq, 45.0)},
        rng=rng,
    )

    bands = [(3e9 + i * 10e6, 3e9 + (i + 1) * 10e6) for i in range(5)]
    scheduler = UCBPriorScheduler(bands_hz=bands, dwell_ms=10.0, seed=42)

    runner = MissionRunner(
        engine=engine,
        detector=detector,
        scheduler=scheduler,
        ground_truth=specs,
        mission_duration_s=0.2, # 20 dwells
        max_dwells=20,
    )

    state, score = runner.run()

    # Verify UCB1 visited all 5 bands in initialization
    assert scheduler.policy.counts.sum() >= 5
    # Verify band 2 (with the emitter) received hits and highest pulls
    band_2_idx = 2
    assert scheduler.policy.reward_sums[band_2_idx] > 0, "Band 2 should have positive reward"
    # End episode diagnostics from ClassicalUCB1
    diag = scheduler.policy.end_episode(training=False)
    assert diag["algorithm"] == "ucb1"
    assert len(diag["band_selection_counts"]) == 5
    assert diag["total_decisions"] > 0
    print("UCB-Prior decisions successful:", diag)
